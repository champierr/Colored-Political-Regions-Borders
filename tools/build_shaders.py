"""Builds the CPR&B shader variants shipped with the patcher.

For every size in VARIANTS writes shaders/cprb_cells.fxh (parameters and the unrolled nearest-center
search for that many centers) and compiles shaders/mb.fx into patcher/shaders/<size>/mb_2a.fxo and
mb_2b.fxo. The patcher installs the smallest variant that fits the mod, since every center slot costs
shader time whether it is used or not.
"""
import os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(ROOT, "shaders")
OUT = os.path.join(ROOT, "patcher", "shaders")

VARIANTS = [192, 256, 320]        # max centers; 320 is the most that fits the constant registers
MAX_FACTIONS = 96                 # palette size, 4 factions per register


def write_cells(num_centers):
  pairs = (num_centers + 1) // 2
  groups = (MAX_FACTIONS + 3) // 4
  lines = ["// Generated by tools/build_shaders.py - do not edit.",
           "#define CPRB_MAX_CENTERS %d" % num_centers,
           "#define CPRB_MAX_FACTIONS %d" % MAX_FACTIONS]
  lines += ["float4 cprbp%d = 0;" % k for k in range(pairs)]
  lines += ["float4 cprbc%d = 0;" % k for k in range(groups)]
  # CPRB_PALETTE(group, owner, one): group = the cprbcK holding faction <owner>. The threshold runs
  # through <one> (always 1, from the vertex shader) so the compiler cannot turn every step into a
  # constant of its own: the constant registers are already full of centers.
  lines += ["#define CPRB_PALETTE(group, owner, one) \\", "\tgroup = cprbc0; \\", "\tfloat threshold = 3.5f * (one); \\"]
  lines += ["\tgroup = ((owner) > threshold) ? cprbc%d : group;  threshold += 4.0f * (one); \\" % g
            for g in range(1, groups)]
  lines += [""]
  lines += ["#define CPRB_SEARCH \\"] + ["\tCPRB_PAIR(cprbp%d) \\" % k for k in range(pairs)] + [""]
  with open(os.path.join(SHADERS, "cprb_cells.fxh"), "w") as f:
    f.write("\n".join(lines) + "\n")


def compile_variant(num_centers):
  write_cells(num_centers)
  out_dir = os.path.join(OUT, str(num_centers))
  os.makedirs(out_dir, exist_ok=True)
  for ps, name in (("ps_2_a", "mb_2a.fxo"), ("ps_2_b", "mb_2b.fxo")):
    r = subprocess.run([os.path.join(SHADERS, "fxc.exe"), "/nologo", "/D", "PS_2_X=" + ps, "/T", "fx_2_0",
                        "/Fo", os.path.join(out_dir, name), "mb.fx"],
                       cwd=SHADERS, capture_output=True, text=True)
    errors = [l for l in (r.stdout + r.stderr).splitlines() if "error" in l.lower()]
    if r.returncode != 0 or errors:
      print("variant %d (%s) FAILED:\n  %s" % (num_centers, ps, "\n  ".join(errors[:5])))
      return False
  print("variant %d ok" % num_centers)
  return True


def main():
  sizes = [int(a) for a in sys.argv[1:]] or VARIANTS
  ok = all([compile_variant(n) for n in sizes])
  sys.exit(0 if ok else 1)


if __name__ == "__main__":
  main()
